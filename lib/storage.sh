#!/usr/bin/env bash
# lib/storage.sh - Supabase Storage's upload size limit, and checks that an
# upload of that size can actually get through.
#
# Storage enforces min(bucket limit, global limit). Upstream's
# docker-compose.yml hard-codes the global one as FILE_SIZE_LIMIT: 52428800
# (50 MiB) in the storage service's environment - it is not read from .env -
# so the application's 4 GiB app-installers bucket limit never takes effect
# and any installer over 50 MiB is refused.
#
# The override is a generated Compose overlay registered in COMPOSE_FILE, the
# same mechanism as the auth hardening overlay (docs/DECISIONS.md #28, #32):
# `update supabase` re-syncs docker-compose.yml from upstream, but never ships
# a file by this name, so the override survives it.
#
# Uploads use TUS in 6 MiB chunks, so a reverse proxy only has to accept one
# chunk per request - but nginx's 1 MB default does not. The checks here read
# the limit Storage advertises (Tus-Max-Size) and, separately, push one
# chunk-sized body through the public URL to catch a proxy that refuses it.
# shellcheck shell=bash

STORAGE_OVERLAY="docker-compose.sentinel-storage.yml"
STORAGE_DEFAULT_FILE_SIZE_LIMIT="4294967296"
# One 6 MiB TUS chunk plus headroom for the request around it.
STORAGE_PROXY_PROBE_BYTES="7340032"

# Non-secret config, persisted in installer.env.
STORAGE_FILE_SIZE_LIMIT="$STORAGE_DEFAULT_FILE_SIZE_LIMIT"

_storage_overlay_path() { printf '%s/%s' "$SUPABASE_DIR" "$STORAGE_OVERLAY"; }

# The configured limit in bytes; a hand-edited value that is not a positive
# integer falls back to the default rather than being written into Compose.
storage_file_size_limit() {
    if [[ "$STORAGE_FILE_SIZE_LIMIT" =~ ^[1-9][0-9]{0,15}$ ]]; then
        printf '%s' "$STORAGE_FILE_SIZE_LIMIT"
    else
        log_warn "STORAGE_FILE_SIZE_LIMIT='${STORAGE_FILE_SIZE_LIMIT}' is not a byte count; using $(human_bytes "$STORAGE_DEFAULT_FILE_SIZE_LIMIT")."
        printf '%s' "$STORAGE_DEFAULT_FILE_SIZE_LIMIT"
    fi
}

# Print the overlay. UPLOAD_FILE_SIZE_LIMIT is set as well because Storage
# prefers it over FILE_SIZE_LIMIT when both exist; an upstream that moved to
# the newer name must not silently bring the 50 MiB limit back.
storage_render_overlay() {
    local limit
    limit="$(storage_file_size_limit)"
    printf '# Generated by sentinel-ops (lib/storage.sh). Do not edit: it is rewritten\n'
    printf '# on every install, `update supabase` and `repair apply` run.\n'
    printf '# Set STORAGE_FILE_SIZE_LIMIT in config/installer.env instead.\n'
    printf 'services:\n'
    printf '  storage:\n'
    printf '    environment:\n'
    printf "      FILE_SIZE_LIMIT: '%s'\n" "$limit"
    printf "      UPLOAD_FILE_SIZE_LIMIT: '%s'\n" "$limit"
}

# Everything storage_apply_config can change, as one string - lets a caller
# tell whether a re-apply actually changed anything (and so needs a restart).
_storage_fingerprint() {
    printf '%s|%s' \
        "$(env_get "${SUPABASE_DIR}/.env" COMPOSE_FILE 2>/dev/null || true)" \
        "$(cat "$(_storage_overlay_path)" 2>/dev/null || true)"
}

# Write the overlay and register it. Safe to call on every install, update
# and repair: the file is only rewritten when its content changes.
storage_apply_config() {
    local env_file="${SUPABASE_DIR}/.env" overlay tmp
    [[ -f "$env_file" ]] || { log_error "Missing ${env_file}"; return 1; }
    overlay="$(_storage_overlay_path)"

    tmp="$(mktemp)"
    storage_render_overlay >"$tmp"
    if ! cmp -s "$tmp" "$overlay" 2>/dev/null; then
        cat "$tmp" >"$overlay"
    fi
    rm -f "$tmp"
    compose_file_register "$env_file" "$STORAGE_OVERLAY" present
    log_ok "Storage upload limit set to $(human_bytes "$(storage_file_size_limit)")"
    return 0
}

# True when the overlay is on disk and listed in COMPOSE_FILE.
storage_overlay_registered() {
    local current
    [[ -f "$(_storage_overlay_path)" ]] || return 1
    current="$(env_get "${SUPABASE_DIR}/.env" COMPOSE_FILE 2>/dev/null || true)"
    [[ ":${current}:" == *":${STORAGE_OVERLAY}:"* ]]
}

# Recreate the storage container so it reads the new environment.
storage_restart() {
    run_logged "restart storage" bash -c "$(_supabase_compose_cmd) up -d --force-recreate storage"
}

# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------

# Pull Tus-Max-Size out of a block of response headers on stdin.
_storage_parse_tus_max_size() {
    local line value=""
    while IFS= read -r line; do
        line="${line%$'\r'}"
        if [[ "${line,,}" == tus-max-size:* ]]; then
            value="${line#*:}"
            value="${value//[[:space:]]/}"
        fi
    done
    [[ "$value" =~ ^[0-9]+$ ]] || return 1
    printf '%s' "$value"
}

_storage_apikey_args() {
    local key
    key="$(supabase_publishable_key 2>/dev/null || true)"
    [[ -n "$key" ]] && printf '%s\n' -H "apikey: ${key}"
    return 0
}

# The upload limit Storage advertises at <base-url>, in bytes. The TUS
# OPTIONS route needs no JWT, but the gateway rejects every route without an
# apikey (see supabase_check_api). storage_upload_limit <base-url>
storage_upload_limit() {
    local base args=() headers
    base="$(strip_trailing_slash "$1")"
    mapfile -t args < <(_storage_apikey_args)
    headers="$(curl -s -o /dev/null -D - --max-time 10 -X OPTIONS \
        -H 'Tus-Resumable: 1.0.0' "${args[@]}" \
        "${base}/storage/v1/upload/resumable" 2>/dev/null)" || return 1
    _storage_parse_tus_max_size <<<"$headers"
}

# The HTTP status for one chunk-sized TUS PATCH against an upload that does
# not exist. Storage answers that with a 4xx of its own; a 413 can only come
# from something in front of it refusing the body. 000 means no answer.
# storage_proxy_body_code <base-url>
storage_proxy_body_code() {
    local base args=() code
    base="$(strip_trailing_slash "$1")"
    mapfile -t args < <(_storage_apikey_args)
    code="$(head -c "$STORAGE_PROXY_PROBE_BYTES" /dev/zero | curl -s -o /dev/null \
        -w '%{http_code}' --max-time 60 -X PATCH \
        -H 'Tus-Resumable: 1.0.0' -H 'Upload-Offset: 0' \
        -H 'Content-Type: application/offset+octet-stream' "${args[@]}" \
        --data-binary @- \
        "${base}/storage/v1/upload/resumable/sentinel-ops-probe-$(random_token 8)" 2>/dev/null)"
    printf '%s' "${code:-000}"
}

# One status line for an advertised limit against the configured one.
# _storage_limit_line <label> <advertised-bytes|""> <configured-bytes>
_storage_limit_line() {
    local label="$1" have="$2" want="$3"
    if [[ -z "$have" ]]; then
        status_line "$label" "warn" "Storage did not report a limit (no Tus-Max-Size)"
    elif (( have < want )); then
        status_line "$label" "warn" "$(human_bytes "$have"), expected $(human_bytes "$want") - run: sentinel-ops repair apply"
    else
        status_line "$label" "ok" "$(human_bytes "$have")"
    fi
}

# Status lines for the upload limit: through the gateway (proves Storage's own
# configuration) and through SUPABASE_PUBLIC_URL when that is somewhere else
# (proves the public route reaches Storage at all).
storage_status() {
    local want gateway have
    want="$(storage_file_size_limit 2>/dev/null)"
    gateway="http://localhost:$(supabase_kong_port)"
    have="$(storage_upload_limit "$gateway" || true)"
    _storage_limit_line "Upload limit" "$have" "$want"

    if [[ "$(strip_trailing_slash "$SUPABASE_PUBLIC_URL")" != "$gateway" ]]; then
        if have="$(storage_upload_limit "$SUPABASE_PUBLIC_URL")"; then
            _storage_limit_line "Upload (public)" "$have" "$want"
        else
            status_line "Upload (public)" "warn" "${SUPABASE_PUBLIC_URL} not reachable from this host; not checked"
        fi
    fi
    return 0
}

# Status line for whether the reverse proxy accepts one upload chunk. Sends
# 7 MiB, so it belongs to `domain`, not to the routine `status`.
storage_proxy_status() {
    local code
    code="$(storage_proxy_body_code "$SUPABASE_PUBLIC_URL")"
    case "$code" in
        413)
            status_line "Proxy uploads" "bad" "The reverse proxy refuses a 6 MiB upload chunk (413) - see docs/REVERSE-PROXY.md" ;;
        000)
            status_line "Proxy uploads" "warn" "${SUPABASE_PUBLIC_URL} not reachable from this host; not checked" ;;
        *)
            status_line "Proxy uploads" "ok" "Accepts a 6 MiB upload chunk" ;;
    esac
    return 0
}
